void NodeEditorWindow::renderPagesPanel()
{
	NodeGraphPtr nodeGraph= getNodeGraph();
	if (!nodeGraph)
	{
		return;
	}

	// A delete mutates the page map, so it is applied after the list has rendered
	t_graph_page_id pendingDeletePageId= -1;

	{
		MkGuiScopedStyle selectionStyle(m_styleManager->getStyle("node_editor_variable_list"));

		const auto renderPageRow=
			[&](GraphPagePtr page, t_graph_page_id pageId, const char* icon, const std::string& title)
		{
			const bool bIsRootPage= (pageId == NodeGraph::k_rootPageId);

			ImGui::TextUnformatted(icon);
			ImGui::SameLine();

			// A row being renamed shows the field in place of its label. The page
			// validates the name itself and a refused one leaves the old name.
			if (page && m_pageRename.isEditing(pageId))
			{
				const MkGui::eInlineRenameResult result= MkGui::drawInlineRenameField(
					m_pageRename, StringUtils::stringify("##rename_page", std::to_string(pageId)));
				if (result == MkGui::eInlineRenameResult::committed)
				{
					page->editorRename(m_pageRename.buffer);
				}
				return;
			}

			// The current page draws selected; the row click also selects the
			// page object so the Details panel shows its sheet
			const bool bWasCurrent= m_editorState.currentPageId == pageId;
			const std::string rowLabel= StringUtils::stringify(title, "##page", std::to_string(pageId));
			if (ImGui::Selectable(rowLabel.c_str(), bWasCurrent))
			{
				setCurrentPage(pageId);
				clearCanvasSelection();
				if (bIsRootPage)
				{
					m_objectSelection.clear();
				}
				else
				{
					m_objectSelection= GraphObjectSelection(GraphObjectIdType::PAGE, 1);
					m_objectSelection.setObjectId(0, pageId);
				}
			}
			if (page && page->editorCanRename()
				&& MkGui::isRenameClickOnSelectedItem(bWasCurrent, pageId, m_pageRenamePressedId))
			{
				m_pageRename.begin(pageId, page->getName());
			}

			if (!bIsRootPage)
			{
				MkGuiScopedStyle pageContextMenuStyle(m_styleManager->getStyle("node_editor_context_menu"));
				MkGuiScopedPopupContextItem pageContextMenu;
				if (pageContextMenu)
				{
					clearCanvasSelection();
					m_objectSelection= GraphObjectSelection(GraphObjectIdType::PAGE, 1);
					m_objectSelection.setObjectId(0, pageId);

					if (ImGui::MenuItem(locLabel("nodeEditor.delete"), ICON_FK_TRASH, "DELETE"))
					{
						pendingDeletePageId= pageId;
					}
				}
			}
		};

		renderPageRow(GraphPagePtr(), NodeGraph::k_rootPageId, ICON_FK_HOME, locText("nodeEditor.rootPage"));
		for (const auto& pageEntry : nodeGraph->getPages())
		{
			GraphPagePtr page= pageEntry.second;
			renderPageRow(page, page->getId(), page->editorGetIcon(), page->editorGetTitle());
		}
	}

	if (pendingDeletePageId != -1)
	{
		nodeGraph->deletePage(pendingDeletePageId);
	}

	ImGui::Separator();

	// One add button per page kind the graph can hold
	for (const auto& factoryEntry : nodeGraph->getPageFactories())
	{
		GraphPageFactoryPtr pageFactory= factoryEntry.second;
		const std::string buttonLabel= StringUtils::stringify(
			ICON_FK_PLUS_CIRCLE "  ", pageFactory->editorGetCreateLabel(), "##", pageFactory->getPageClassName());

		if (ImGui::SmallButton(buttonLabel.c_str()))
		{
			// The created delegate switches the canvas to the new page
			nodeGraph->createPage(pageFactory, m_editorState);
		}
	}
}

void NodeEditorWindow::renderAssetsPanel()
{
	NodeGraphPtr nodeGraph= getNodeGraph();

	MkGuiScopedChild assetSubFrame("AssetSubFrame");

	// The project's assets of the types this graph accepts, drawn as drag sources
	// for the canvas and the variables panel. Assets are imported and authored
	// from the project's Assets panel, so there is no toolbar here.
	ProjectAssetCatalog* catalog= getAssetCatalog();
	if (!nodeGraph || catalog == nullptr)
	{
		return;
	}

	const std::vector<AssetReferenceFactoryPtr> validFactories=
		nodeGraph->editorGetValidAssetRefFactories(m_editorState);

	MkGuiScopedChild assetBrowser("AssetBrowser");

	ImGui::Dummy(ImVec2(1, 10));

	// The payload carries the catalog's instance, which a receiver maps to the
	// graph's own reference before binding anything to it
	auto attachDragAndOpen= [&](AssetReferencePtr assetRef, const ProjectAssetEntry& entry, bool bDoubleClicked)
	{
		{
			MkGuiScopedDragDropSource dds(ImGuiDragDropFlags_None);
			if (dds)
			{
				ImGui::SetDragDropPayload(assetRef->getClassName().c_str(), &assetRef, sizeof(AssetReferencePtr));
				ImGui::TextUnformatted(entry.displayName.c_str());
			}
		}

		if (bDoubleClicked && assetRef->editorCanOpen())
		{
			assetRef->editorOpen();
		}
	};

	bool bAnyEntryDrawn= false;
	for (const ProjectAssetFolderDesc& folderDesc : ProjectAssetCatalog::getFolderDescs())
	{
		// The folder's entries this graph accepts
		std::vector<const ProjectAssetEntry*> matchingEntries;
		for (const ProjectAssetEntry& entry : catalog->getEntries(folderDesc.id))
		{
			const bool bMatchesGraph=
				std::any_of(validFactories.begin(), validFactories.end(), [&](AssetReferenceFactoryPtr factory)
							{ return catalog->entryMatchesFactory(entry, *factory); });
			if (bMatchesGraph)
			{
				matchingEntries.push_back(&entry);
			}
		}
		if (matchingEntries.empty())
		{
			continue;
		}

		// One divider between folder groups (materials above textures), none above the first
		if (bAnyEntryDrawn)
		{
			ImGui::Separator();
		}
		bAnyEntryDrawn= true;

		if (folderDesc.bPreviewTiles)
		{
			for (const ProjectAssetEntry* entry : matchingEntries)
			{
				AssetReferencePtr assetRef= catalog->getAssetReference(*entry);
				if (!assetRef)
					continue;

				const AssetTileGui::ItemResult tile= AssetTileGui::beginTile("##asset" + entry->key(), false);
				attachDragAndOpen(assetRef, *entry, tile.bDoubleClicked);
				AssetTileGui::endTile(assetRef, entry->displayName);
			}
			ImGui::NewLine();
		}
		else if (AssetTileGui::beginList(("##assetList" + folderDesc.id).c_str()))
		{
			for (const ProjectAssetEntry* entry : matchingEntries)
			{
				AssetReferencePtr assetRef= catalog->getAssetReference(*entry);
				if (!assetRef)
					continue;

				const AssetTileGui::ItemResult row= AssetTileGui::drawListItem(
					"##asset" + entry->key(), assetRef->editorGetIcon(), entry->displayName, false);
				attachDragAndOpen(assetRef, *entry, row.bDoubleClicked);
			}
			AssetTileGui::endList();
		}
	}

	if (!bAnyEntryDrawn)
	{
		ImGui::TextDisabled("%s", locText("assets.empty"));
	}

	ImGui::Dummy(ImVec2(1, 10));
}

void NodeEditorWindow::renderSelectedObjectPanel()
{
	if (m_objectSelection.getObjectIdType() == GraphObjectIdType::NODE)
	{
		NodePtr node= getNodeGraph()->getNodeById(m_objectSelection.getObjectId(0));

		if (node)
		{
			node->editorRenderPropertySheet(m_editorState);
		}
	}
	else if (m_objectSelection.getObjectIdType() == GraphObjectIdType::VARIABLE)
	{
		GraphPropertyPtr property= getNodeGraph()->getPropertyById(m_objectSelection.getObjectId(0));

		if (property)
		{
			renderVariableNameField(property);
			property->editorRenderPropertySheet(m_editorState);
		}
	}
	else if (m_objectSelection.getObjectIdType() == GraphObjectIdType::PAGE)
	{
		GraphPagePtr page= getNodeGraph()->getPageById(m_objectSelection.getObjectId(0));

		if (page)
		{
			page->editorRenderPropertySheet(m_editorState);
		}
	}
	else if (m_objectSelection.getObjectIdType() == GraphObjectIdType::NONE)
	{
		// Nothing selected: the graph's own settings take the panel
		NodeGraphPtr nodeGraph= getNodeGraph();
		if (nodeGraph)
		{
			nodeGraph->editorRenderGraphPropertySheet(m_editorState);
		}
	}
}

void NodeEditorWindow::renderVariableNameField(GraphPropertyPtr property)
{
	// Refill the edit buffer when the selection moves to a different variable
	// or the name changed elsewhere (the inline rename, automation, undo),
	// leaving in-progress typing alone otherwise
	const bool bNameChangedOutside= !m_bVariableNameFieldActive && property->getName() != m_variableNameBuffer;
	if (m_variableNameBufferId != property->getId() || bNameChangedOutside)
	{
		m_variableNameBufferId= property->getId();
		strncpy(m_variableNameBuffer, property->getName().c_str(), sizeof(m_variableNameBuffer) - 1);
		m_variableNameBuffer[sizeof(m_variableNameBuffer) - 1]= '\0';
	}

	MkGuiStyleConstPtr propertyStyle= m_styleManager->getStyle("node_editor_property_value");
	// The label is drawn as plain text and the field id comes from the fieldName
	// argument, so this takes locText rather than locLabel
	if (MkGui::drawStringProperty(propertyStyle, "variableName", locText("nodeEditor.variableName"),
								  m_variableNameBuffer, sizeof(m_variableNameBuffer)))
	{
		const std::string typedName= m_variableNameBuffer;
		const size_t firstIndex= typedName.find_first_not_of(" \t");
		const size_t lastIndex= typedName.find_last_not_of(" \t");
		const std::string newName= (firstIndex == std::string::npos)
									   ? std::string()
									   : typedName.substr(firstIndex, lastIndex - firstIndex + 1);

		// The graph keeps the name unique, so an all-space or duplicate entry
		// lands as nothing or as a suffixed name
		getNodeGraph()->renameProperty(property->getId(), newName);

		// Reflect whatever the property actually kept
		strncpy(m_variableNameBuffer, property->getName().c_str(), sizeof(m_variableNameBuffer) - 1);
		m_variableNameBuffer[sizeof(m_variableNameBuffer) - 1]= '\0';
	}
	m_bVariableNameFieldActive= ImGui::IsItemActive();
}

void NodeEditorWindow::beginSelectedObjectRename()
{
	NodeGraphPtr nodeGraph= getNodeGraph();
	if (!nodeGraph || m_objectSelection.getObjectCount() < 1)
		return;

	if (m_objectSelection.getObjectIdType() == GraphObjectIdType::VARIABLE)
	{
		if (GraphPropertyPtr property= nodeGraph->getPropertyById(m_objectSelection.getObjectId(0)))
		{
			m_variableRename.begin(property->getId(), property->getName());
		}
	}
	else if (m_objectSelection.getObjectIdType() == GraphObjectIdType::PAGE)
	{
		GraphPagePtr page= nodeGraph->getPageById(m_objectSelection.getObjectId(0));
		if (page && page->editorCanRename())
		{
			m_pageRename.begin(page->getId(), page->getName());
		}
	}
}

void NodeEditorWindow::deleteSelectedItem()
{
	if (m_objectSelection.getObjectIdType() == GraphObjectIdType::NODE)
	{
		for (int i= 0; i < m_objectSelection.getObjectCount(); i++)
		{
			const t_node_id nodeId= m_objectSelection.getObjectId(i);
			NodePtr node= getNodeGraph()->getNodeById(nodeId);

			if (node && node->editorCanDelete())
			{
				getNodeGraph()->deleteNodeById(nodeId);
			}
		}

		m_objectSelection.clear();
	}
	else if (m_objectSelection.getObjectIdType() == GraphObjectIdType::LINK)
	{
		for (int i= 0; i < m_objectSelection.getObjectCount(); i++)
		{
			const t_node_link_id linkId= m_objectSelection.getObjectId(i);

			getNodeGraph()->deleteLinkById(linkId);
		}

		m_objectSelection.clear();
	}
	else if (m_objectSelection.getObjectIdType() == GraphObjectIdType::VARIABLE)
	{
		for (int i= 0; i < m_objectSelection.getObjectCount(); i++)
		{
			const t_graph_property_id propertyId= m_objectSelection.getObjectId(i);

			getNodeGraph()->deletePropertyById(propertyId);
		}

		m_objectSelection.clear();
	}
	else if (m_objectSelection.getObjectIdType() == GraphObjectIdType::PAGE)
	{
		for (int i= 0; i < m_objectSelection.getObjectCount(); i++)
		{
			const t_graph_page_id pageId= m_objectSelection.getObjectId(i);

			getNodeGraph()->deletePage(pageId);
		}

		m_objectSelection.clear();
	}
}

