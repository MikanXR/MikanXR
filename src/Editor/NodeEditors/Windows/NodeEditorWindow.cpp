bool NodeEditorWindow::startup()
{
	EASY_FUNCTION();

	bool success= true;

	MIKAN_LOG_INFO("NodeEditorWindow::init()") << "Initializing NodeEditorWindow";

	static const int k_node_window_pixel_width= 1080;
	static const int k_node_window_pixel_height= 720;

	if (success && !startupWindow(locText(getWindowTitleKey()), k_node_window_pixel_width, k_node_window_pixel_height))
	{
		success= false;
	}

	if (success && !startupGuiContext(getGuiIniName(), /*bEnableDocking=*/true))
	{
		success= false;
	}

	if (success && !startupStyleManager())
	{
		success= false;
	}

	if (success)
	{
		m_editorState.styleManager= m_styleManager.get();
	}

	if (success)
	{
		// The canvas context must be created while this window's ImGui context
		// is current, since the library binds to ImGui::GetCurrentContext()
		MkGuiScopedContext scopedContext(*m_guiContext.get());

		m_canvasContext= MkCanvas::createEditorContext();
		success= (m_canvasContext != nullptr);
		if (success)
		{
			MkCanvas::applyEditorStyle(m_canvasContext);
		}
	}

	if (success && !startupTextureCache())
	{
		success= false;
	}

	if (success && !startupModelResourceManager())
	{
		success= false;
	}

	return success;
}

void NodeEditorWindow::update(float deltaSeconds)
{
	EASY_FUNCTION();

	// Run parked automation work and scheduled history steps outside the
	// ImGui frame, where graph rebuilds and context pushes are safe
	flushAutomationTasks();
	if (m_pendingHistorySteps != 0)
	{
		const int steps= m_pendingHistorySteps;
		m_pendingHistorySteps= 0;
		stepHistory(steps);
	}

	// Push the ImGui Update scope
	MkGuiScopedUpdate scopedCtx(*m_guiContext);

	// The scope above refreshed the UI scale, so the canvas can be brought along
	// before anything reads a node position this frame
	refreshCanvasUiScale();

	// Process most recent SDL events (keyboard, mouse, etc)
	m_mkWindowContext->handleEvents(this);

	// Process UI input and build ImGui draw lists
	updateUI();

	// On Pop: Finalize draw lists and clear ImGui context
}

void NodeEditorWindow::render()
{
	EASY_FUNCTION();

	// Clear the window
	m_graphicsContext->renderBegin();

	{
		// Create a scoped UI rendering settings
		MkScopedState scopedState= m_graphicsContext->getMkStateStack().createScopedState("appStage renderUI");
		IMkState* glState= scopedState.getStackState();

		mkStateSetViewport(glState, 0, 0, (int)m_mkWindowContext->getWidth(), (int)m_mkWindowContext->getHeight());

		// Submit the MkGui draw calls
		m_guiContext->submitDrawData();
	}

	// Finalize rendering
	m_graphicsContext->renderEnd();

	// Present the rendered frame
	presentFrame();
}

void NodeEditorWindow::updateUI()
{
	MkGuiScopedStyle baseStyle(m_styleManager->getStyle("node_editor_base"));

	bool bNeedsDefaultLayout= false;
	const ImGuiID dockspaceId= MkGui::beginDockspaceHost("##NodeEditorDockHost", "NodeEditorDockspace",
														 bNeedsDefaultLayout, m_bResetLayoutRequested);
	m_bResetLayoutRequested= false;
	if (bNeedsDefaultLayout)
	{
		buildDefaultDockLayout((unsigned int)dockspaceId);
		MkGui::dockBuilderFinish(dockspaceId);
	}

	if (ImGui::BeginMenuBar())
	{
		renderMenuBar();
		ImGui::EndMenuBar();
	}

	// Each panel is its own dockable window; the View menu toggles all but the graph
	{
		MkGuiScopedWindow graphWindow(locWindowTitle("windows.nodeGraphPanel"));
		if (graphWindow)
		{
			renderMainFrame();
		}
	}

	if (m_bShowVariablesPanel)
	{
		MkGuiScopedWindow variablesWindow(locWindowTitle("windows.nodeVariablesPanel"), &m_bShowVariablesPanel);
		if (variablesWindow)
		{
			renderGraphVariablesPanel();
		}
	}

	if (m_bShowPagesPanel && hasPagesPanel())
	{
		MkGuiScopedWindow pagesWindow(locWindowTitle(getPagesPanelTitleKey()), &m_bShowPagesPanel);
		if (pagesWindow)
		{
			renderPagesPanel();
		}
	}

	if (m_bShowAssetsPanel)
	{
		MkGuiScopedWindow assetsWindow(locWindowTitle("windows.nodeAssetsPanel"), &m_bShowAssetsPanel);
		if (assetsWindow)
		{
			renderAssetsPanel();
		}
	}

	if (m_bShowDetailsPanel)
	{
		MkGuiScopedWindow detailsWindow(locWindowTitle("windows.nodeDetailsPanel"), &m_bShowDetailsPanel);
		if (detailsWindow)
		{
			renderSelectedObjectPanel();
		}
	}

	MkGui::endDockspaceHost();

	LocDebugUI::drawWindows(m_bShowIdStackTool);
	LocDebugUI::handleShortcuts();

	// Keyboard chords; text fields keep ImGui's own undo
	const ImGuiIO& io= ImGui::GetIO();
	if (ImGui::IsKeyPressed(ImGuiKey_Z, false) && io.KeyCtrl && !ImGui::IsAnyItemActive())
	{
		if (io.KeyShift)
		{
			redo();
		}
		else
		{
			undo();
		}
	}
	if (ImGui::IsKeyPressed(ImGuiKey_F2, false) && !ImGui::IsAnyItemActive())
	{
		beginSelectedObjectRename();
	}
	if (ImGui::IsKeyPressed(ImGuiKey_S, false) && io.KeyCtrl && !ImGui::IsAnyItemActive())
	{
		saveGraph(false);
	}

	updateHistoryCapture();
}

void NodeEditorWindow::renderMenuBar()
{
	if (ImGui::BeginMenu(locLabel("mainWindow.fileMenu")))
	{
		if (ImGui::MenuItem(locLabel("nodeEditor.save"), "Ctrl+S"))
		{
			saveGraph(false);
		}
		if (ImGui::MenuItem(locLabel("nodeEditor.saveAs")))
		{
			saveGraph(true);
		}
		ImGui::EndMenu();
	}

	if (ImGui::BeginMenu(locLabel("nodeEditor.editMenu")))
	{
		if (ImGui::MenuItem(locLabel("nodeEditor.undo"), "Ctrl+Z", false, canUndo()))
		{
			undo();
		}
		if (ImGui::MenuItem(locLabel("nodeEditor.redo"), "Ctrl+Shift+Z", false, canRedo()))
		{
			redo();
		}
		ImGui::EndMenu();
	}

	if (ImGui::BeginMenu(locLabel("mainWindow.viewMenu")))
	{
		ImGui::MenuItem(locLabel("nodeEditor.variables"), nullptr, &m_bShowVariablesPanel);
		if (hasPagesPanel())
		{
			ImGui::MenuItem(locLabel("nodeEditor.pages"), nullptr, &m_bShowPagesPanel);
		}
		ImGui::MenuItem(locLabel("nodeEditor.assetsTab"), nullptr, &m_bShowAssetsPanel);
		ImGui::MenuItem(locLabel("nodeEditor.details"), nullptr, &m_bShowDetailsPanel);
		renderViewMenuExtras();
		ImGui::Separator();
		LocDebugUI::drawViewMenuItems(m_bShowIdStackTool);
		ImGui::Separator();
		if (ImGui::MenuItem(locLabel("nodeEditor.resetLayout")))
		{
			m_bShowVariablesPanel= true;
			m_bShowPagesPanel= true;
			m_bShowAssetsPanel= true;
			m_bShowDetailsPanel= true;
			m_bResetLayoutRequested= true;
		}
		ImGui::EndMenu();
	}

	renderMenuBarExtras();
}

void NodeEditorWindow::buildDefaultDockLayout(unsigned int dockspaceId)
{
	ImGuiID remaining= (ImGuiID)dockspaceId;
	const ImGuiID leftId= MkGui::dockBuilderSplit(remaining, ImGuiDir_Left, 0.18f, remaining);
	ImGuiID rightId= MkGui::dockBuilderSplit(remaining, ImGuiDir_Right, 0.25f, remaining);
	const ImGuiID bottomId= MkGui::dockBuilderSplit(remaining, ImGuiDir_Down, 0.28f, remaining);

	// Subclass panels carve their nodes out of the right column first
	unsigned int rightRemaining= (unsigned int)rightId;
	dockExtraPanels(rightRemaining);
	rightId= (ImGuiID)rightRemaining;

	// Pages sit above Variables in the left column
	ImGuiID leftRemaining= leftId;
	if (hasPagesPanel())
	{
		const ImGuiID pagesId= MkGui::dockBuilderSplit(leftRemaining, ImGuiDir_Up, 0.4f, leftRemaining);
		MkGui::dockBuilderDockWindow(locWindowTitle(getPagesPanelTitleKey()), pagesId);
	}

	MkGui::dockBuilderDockWindow(locWindowTitle("windows.nodeVariablesPanel"), leftRemaining);
	MkGui::dockBuilderDockWindow(locWindowTitle("windows.nodeDetailsPanel"), rightId);
	MkGui::dockBuilderDockWindow(locWindowTitle("windows.nodeAssetsPanel"), bottomId);
	MkGui::dockBuilderDockWindow(locWindowTitle("windows.nodeGraphPanel"), remaining);
}

void NodeEditorWindow::renderMainFrame()
{
	NodeGraphPtr nodeGraph= getNodeGraph();

	// Interaction results gathered inside the canvas scope but acted on after
	// it closes: popups and graph mutations stay out of the canvas transform
	bool bOpenNodeMenu= false;
	bool bOpenPinMenu= false;
	bool bOpenLinkMenu= false;
	bool bOpenBackgroundMenu= false;
	struct PendingLinkCreate
	{
		int startPinId;
		int endPinId;
	};
	std::vector<PendingLinkCreate> pendingLinkCreates;
	std::vector<t_node_link_id> pendingLinkDeletes;
	std::vector<t_node_id> pendingNodeDeletes;
	std::vector<ImVec2> evalErrorScreenPositions;

	// Breadcrumb: one line naming the page the canvas shows, with the root
	// segment clickable from any other page
	if (nodeGraph && nodeGraph->hasPageFactories())
	{
		GraphPagePtr currentPage= nodeGraph->getPageById(m_editorState.currentPageId);
		if (currentPage)
		{
			if (ImGui::SmallButton(locLabel("nodeEditor.rootPage")))
			{
				setCurrentPage(NodeGraph::k_rootPageId);
			}
			ImGui::SameLine();
			ImGui::Text("%s %s %s", ICON_FK_ANGLE_RIGHT, currentPage->editorGetIcon(),
						currentPage->editorGetTitle().c_str());
		}
		else
		{
			ImGui::TextUnformatted(locText("nodeEditor.rootPage"));
		}
	}

	{
		MkCanvasScopedEditor scopedEditor(m_canvasContext, "GraphCanvas");

		if (nodeGraph)
		{
			nodeGraph->editorRender(m_editorState);

			// The content bounds only cover nodes submitted this frame, so a
			// page switch frames its nodes once they have been drawn
			if (m_bNavigateToContentPending)
			{
				ed::NavigateToContent();
				m_bNavigateToContentPending= false;
			}

			// A double-click on a node body opens whatever the node edits (a material graph, a script)
			const int doubleClickedNodeId= MkCanvas::getDoubleClickedNodeId();
			if (doubleClickedNodeId != -1)
			{
				NodePtr doubleClickedNode= nodeGraph->getNodeById(doubleClickedNodeId);
				if (doubleClickedNode)
				{
					doubleClickedNode->editorOnDoubleClicked(m_editorState);
				}
			}
		}

		// Inside Begin/End the canvas remaps io.MousePos into canvas space, so
		// the raw mouse position is already the node-placement position, carried
		// back to the logical units node positions are stored in
		const ImVec2 mouseGraphPos= MkCanvas::fromCanvasSpace(ImGui::GetMousePos());

		// Track the drop position while an asset/variable drag is in flight
		// (onNodeCreated places new nodes from hangPosGridSpace)
		if (ImGui::GetDragDropPayload() != nullptr)
		{
			m_editorState.hangPosGridSpace= mouseGraphPos;
		}

		// Link creation, with live accept/reject feedback from pin compatibility.
		//
		// EndCreate() is only legal after a BeginCreate() that returned true: the
		// action only marks itself active once it has a drag to report, and its
		// End() asserts on that flag rather than tolerating the unpaired call.
		// Calling it unconditionally therefore fires on every frame that is not
		// mid-drag, which is nearly all of them. It went unnoticed because
		// IM_ASSERT is assert(), so only a debug build trips it.
		// Ctrl+press on a connected pin picks up that link's end: the editor is
		// told to drag from the far pin, the link hides while carried, and the
		// graph changes only on release (rewire on a pin, delete on the canvas).
		// One link at a time: an input holds at most one, an output qualifies
		// only while it holds exactly one.
		if (nodeGraph && m_editorState.detachedLinkId == -1 && ImGui::GetIO().KeyCtrl
			&& ImGui::IsMouseClicked(ImGuiMouseButton_Left))
		{
			const ed::PinId hoveredPinId= ed::GetHoveredPin();
			NodePinPtr heldPin= hoveredPinId.Get() != 0
									? nodeGraph->getPinById(MkCanvas::fromCanvasId((int)hoveredPinId.Get()))
									: NodePinPtr();
			if (heldPin && heldPin->getConnectedLinks().size() == 1)
			{
				NodeLinkPtr heldLink= heldPin->getConnectedLinks()[0];
				NodePinPtr anchorPin= heldLink->getConnectedPin(heldPin);
				if (anchorPin)
				{
					ed::SetLinkDragAnchor(MkCanvas::toCanvasId(anchorPin->getId()));
					m_editorState.detachedLinkId= heldLink->getId();
					m_detachHeldPinId= heldPin->getId();
					m_detachAnchorPinId= anchorPin->getId();
				}
			}
		}

		const bool bCreateStarted= ed::BeginCreate();
		if (bCreateStarted)
		{
			const bool bDetachInFlight= m_editorState.detachedLinkId != -1;
			ed::PinId startPinId, endPinId;
			ed::PinId hangPinId;
			if (ed::QueryNewLink(&startPinId, &endPinId))
			{
				const int startGraphPinId= MkCanvas::fromCanvasId((int)startPinId.Get());
				const int endGraphPinId= MkCanvas::fromCanvasId((int)endPinId.Get());
				m_editorState.startedLinkPinId= startGraphPinId;

				NodePinPtr startPin= nodeGraph ? nodeGraph->getPinById(startGraphPinId) : NodePinPtr();
				NodePinPtr endPin= nodeGraph ? nodeGraph->getPinById(endGraphPinId) : NodePinPtr();
				if (bDetachInFlight && endGraphPinId == m_detachHeldPinId)
				{
					// Dropped back where it was picked up: the old link stays
					if (ed::AcceptNewItem())
					{
						clearLinkDetach();
					}
				}
				else if (startPin && endPin && startPin->canPinsBeConnected(endPin))
				{
					const ImVec4 previewColor= ImGui::ColorConvertU32ToFloat4(startPin->editorGetLinkStyleColor());
					if (ed::AcceptNewItem(previewColor, 3.f))
					{
						// A rewire deletes the carried link and creates the new one
						// in the same apply pass, so undo sees a single step
						if (bDetachInFlight)
						{
							pendingLinkDeletes.push_back(m_editorState.detachedLinkId);
							clearLinkDetach();
						}
						pendingLinkCreates.push_back({startGraphPinId, endGraphPinId});
					}
				}
				else
				{
					ed::RejectNewItem(ImVec4(1.f, 0.25f, 0.25f, 1.f), 3.f);
				}
			}
			else if (ed::QueryNewNode(&hangPinId))
			{
				m_editorState.startedLinkPinId= MkCanvas::fromCanvasId((int)hangPinId.Get());

				if (bDetachInFlight)
				{
					// A carried link released over the canvas is dropped, not re-homed
					if (ed::AcceptNewItem())
					{
						pendingLinkDeletes.push_back(m_editorState.detachedLinkId);
						clearLinkDetach();
					}
				}
				else if (ed::AcceptNewItem())
				{
					// Link dropped on empty canvas: offer node creation there
					m_editorState.bLinkHanged= true;
					m_editorState.hangPosGridSpace= mouseGraphPos;
					bOpenBackgroundMenu= true;
				}
			}
		}
		else if (!m_editorState.bLinkHanged)
		{
			m_editorState.startedLinkPinId= -1;

			// A Ctrl+press that never became a drag, or a drag the editor
			// cancelled, leaves the link as it was
			if (m_editorState.detachedLinkId != -1 && !ImGui::IsMouseDown(ImGuiMouseButton_Left))
			{
				clearLinkDetach();
			}
		}

		if (bCreateStarted)
		{
			ed::EndCreate();
		}

		// Deletion funnel: the canvas's Del-key and programmatic deletions all
		// arrive here, gated by each node's editorCanDelete
		if (ed::BeginDelete())
		{
			ed::LinkId deletedLinkId;
			while (ed::QueryDeletedLink(&deletedLinkId))
			{
				if (ed::AcceptDeletedItem())
				{
					pendingLinkDeletes.push_back(MkCanvas::fromCanvasId((int)deletedLinkId.Get()));
				}
			}

			ed::NodeId deletedNodeId;
			while (ed::QueryDeletedNode(&deletedNodeId))
			{
				const t_node_id deletedGraphNodeId= MkCanvas::fromCanvasId((int)deletedNodeId.Get());
				NodePtr node= nodeGraph ? nodeGraph->getNodeById(deletedGraphNodeId) : NodePtr();
				if (node && node->editorCanDelete())
				{
					if (ed::AcceptDeletedItem())
					{
						pendingNodeDeletes.push_back(deletedGraphNodeId);
					}
				}
				else
				{
					ed::RejectDeletedItem();
				}
			}
		}
		ed::EndDelete();

		// Node selection sync (filtered against the graph so ids from deleted
		// nodes never linger in the selection)
		if (nodeGraph)
		{
			std::vector<ed::NodeId> selectedNodeIds(ed::GetSelectedObjectCount());
			const int selectedNodeCount= ed::GetSelectedNodes(selectedNodeIds.data(), (int)selectedNodeIds.size());
			std::vector<t_node_id> liveNodeIds;
			for (int index= 0; index < selectedNodeCount; index++)
			{
				const t_node_id nodeId= MkCanvas::fromCanvasId((int)selectedNodeIds[index].Get());
				if (nodeGraph->getNodeById(nodeId))
				{
					liveNodeIds.push_back(nodeId);
				}
			}

			if (!liveNodeIds.empty())
			{
				GraphObjectSelection selection(GraphObjectIdType::NODE, (int)liveNodeIds.size());
				for (int index= 0; index < (int)liveNodeIds.size(); index++)
				{
					selection.setObjectId(index, liveNodeIds[index]);
				}
				m_objectSelection= selection;
			}
		}

		// Context menu queries; popups open after the canvas closes
		ed::NodeId contextNodeId;
		ed::PinId contextPinId;
		ed::LinkId contextLinkId;
		if (ed::ShowNodeContextMenu(&contextNodeId))
		{
			m_objectSelection= GraphObjectSelection(GraphObjectIdType::NODE, 1);
			m_objectSelection.setObjectId(0, MkCanvas::fromCanvasId((int)contextNodeId.Get()));
			ed::SelectNode(contextNodeId);
			bOpenNodeMenu= true;
		}
		else if (ed::ShowPinContextMenu(&contextPinId))
		{
			m_contextPinId= MkCanvas::fromCanvasId((int)contextPinId.Get());
			bOpenPinMenu= true;
		}
		else if (ed::ShowLinkContextMenu(&contextLinkId))
		{
			m_objectSelection= GraphObjectSelection(GraphObjectIdType::LINK, 1);
			m_objectSelection.setObjectId(0, MkCanvas::fromCanvasId((int)contextLinkId.Get()));
			ed::SelectLink(contextLinkId);
			bOpenLinkMenu= true;
		}
		else if (ed::ShowBackgroundContextMenu())
		{
			m_editorState.hangPosGridSpace= mouseGraphPos;
			bOpenBackgroundMenu= true;
		}

		// Eval error overlay anchors (canvas to screen while the canvas is current)
		for (const NodeEvaluationError& evalError : m_lastNodeEvalErrors)
		{
			ImVec2 screenPos(0.f, 0.f);
			if (evalError.errorNodeId != -1)
			{
				screenPos= ed::CanvasToScreen(ed::GetNodePosition(MkCanvas::toCanvasId(evalError.errorNodeId)));
			}
			evalErrorScreenPositions.push_back(screenPos);
		}
	}

	// Drag and drop creation: the canvas child is the last submitted item, so
	// the drop target must attach before any other item renders
	handleMainFrameDragDrop(m_editorState);

	// Apply the gathered graph mutations. Deletes go first: a rewire that lands
	// on an input pin would otherwise have the input's own single-link rule
	// delete the carried link before the queued delete reaches it.
	if (nodeGraph)
	{
		for (t_node_link_id linkId : pendingLinkDeletes)
		{
			nodeGraph->deleteLinkById(linkId);
		}
		for (const PendingLinkCreate& linkCreate : pendingLinkCreates)
		{
			m_editorState.startedLinkPinId= -1;
			nodeGraph->createLink(linkCreate.startPinId, linkCreate.endPinId);
		}
		for (t_node_id nodeId : pendingNodeDeletes)
		{
			nodeGraph->deleteNodeById(nodeId);
		}
	}

	// Draw error messages on top of related nodes
	renderNodeEvalErrors(evalErrorScreenPositions);

	// Context menu popups
	if (bOpenNodeMenu)
	{
		ImGui::OpenPopup("editor_context_menu_node");
	}
	else if (bOpenPinMenu)
	{
		ImGui::OpenPopup("editor_context_menu_pin");
	}
	else if (bOpenLinkMenu)
	{
		ImGui::OpenPopup("editor_context_menu_link");
	}
	else if (bOpenBackgroundMenu)
	{
		ImGui::OpenPopup("editor_context_menu_nodes");
	}
	renderMainFrameContextMenu(m_editorState);
}

void NodeEditorWindow::renderNodeEvalErrors(const std::vector<ImVec2>& errorScreenPositions)
{
	if (m_editorState.nodeGraph && m_lastNodeEvalErrors.size() > 0)
	{
		size_t errorIter= 0;
		while (errorIter < m_lastNodeEvalErrors.size())
		{
			const NodeEvaluationError* currentError= &m_lastNodeEvalErrors[errorIter];
			const std::string evalWindowId=
				StringUtils::stringify(locText("nodeEditor.evalErrorWindowTitle"), "##Node", currentError->errorNodeId);

			static const float k_errorWindowOffset= 50.f;
			ImVec2 errorPos= errorIter < errorScreenPositions.size() ? errorScreenPositions[errorIter] : ImVec2(0, 0);
			errorPos.y-= k_errorWindowOffset;

			ImGui::SetNextWindowPos(errorPos);
			MkGuiScopedWindow evalWindow(evalWindowId.c_str(), nullptr,
										 ImGuiWindowFlags_NoResize | ImGuiWindowFlags_AlwaysAutoResize
											 | ImGuiWindowFlags_NoNav);
			{
				MkGuiScopedGroup errorGroup;
				MkGuiScopedStyle errorTextStyle(m_styleManager->getStyle("node_editor_error_text"));
				while (errorIter < m_lastNodeEvalErrors.size())
				{
					// Add a bullet point for each error on the same node
					ImGui::BulletText("%s", currentError->errorMessage.c_str());

					// Advance to the next error message on this node
					errorIter++;

					// If the next error is on a different node, move on to the next error window
					if (errorIter < m_lastNodeEvalErrors.size())
					{
						const NodeEvaluationError* nextError= &m_lastNodeEvalErrors[errorIter];

						if (nextError->errorNodeId == currentError->errorNodeId)
						{
							currentError= nextError;
						}
						else
						{
							break;
						}
					}
				}
			}
		}
	}
}

void NodeEditorWindow::renderMainFrameContextMenu(const NodeEditorState& editorState)
{
	// The canvas hover queries in renderMainFrame decide which popup opened;
	// this only renders whichever one is active
	MkGuiScopedStyle contextMenuStyle(m_styleManager->getStyle("node_editor_context_menu"));
	{
		MkGuiScopedPopup nodePopup("editor_context_menu_node");
		if (nodePopup)
		{
			NodePtr node;
			if (m_objectSelection.getObjectIdType() == GraphObjectIdType::NODE)
			{
				node= getNodeGraph()->getNodeById(m_objectSelection.getObjectId(0));
			}

			if (node && node->editorCanDelete())
			{
				if (ImGui::MenuItem(locLabel("nodeEditor.delete"), ICON_FK_TRASH, "DELETE"))
				{
					getNodeGraph()->deleteNodeById(m_objectSelection.getObjectId(0));
				}
			}
			else
			{
				ImGui::CloseCurrentPopup();
			}
		}
		else
		{
			MkGuiScopedPopup pinPopup("editor_context_menu_pin");
			if (pinPopup)
			{
				NodePinPtr pin= getNodeGraph() ? getNodeGraph()->getPinById(m_contextPinId) : NodePinPtr();
				if (pin)
				{
					// Disconnect drops every link on the pin; the pin kind may add its own items after it
					if (ImGui::MenuItem(locLabel("nodeEditor.disconnect"), ICON_FK_CHAIN_BROKEN, false,
										pin->hasAnyConnectedLinks()))
					{
						const std::vector<NodeLinkPtr> links= pin->getConnectedLinks();
						for (const NodeLinkPtr& link : links)
						{
							getNodeGraph()->deleteLinkById(link->getId());
						}
					}
					pin->editorRenderContextMenu(editorState);
				}
				else
				{
					ImGui::CloseCurrentPopup();
				}
			}
			else
			{
				MkGuiScopedPopup linkPopup("editor_context_menu_link");
				if (linkPopup)
				{
					if (m_objectSelection.getObjectIdType() == GraphObjectIdType::LINK
						&& ImGui::MenuItem(locLabel("nodeEditor.delete"), ICON_FK_TRASH, "DELETE"))
					{
						getNodeGraph()->deleteLinkById(m_objectSelection.getObjectId(0));
					}
				}
				else
				{
					MkGuiScopedPopup nodesPopup("editor_context_menu_nodes");
					if (nodesPopup)
					{
						NodeGraphPtr nodeGraph= getNodeGraph();
						if (nodeGraph)
						{
							renderCreateNodeMenu(editorState);
						}
					}
					else if (m_editorState.bLinkHanged)
					{
						m_editorState.bLinkHanged= false;
						m_editorState.startedLinkPinId= -1;
					}
				}
			}
		}
	}
}

