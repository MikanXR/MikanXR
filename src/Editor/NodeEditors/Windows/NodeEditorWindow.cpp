void NodeEditorWindow::newGraph()
{
	createNewGraph([this]() { return getNodeGraphFactory()->initialCreateNodeGraph(this); });
}

void NodeEditorWindow::createNewGraph(const std::function<NodeGraphPtr()>& createGraph)
{
	// Push this window's GL context before graph resource creation (VAOs, VBOs).
	// Graph creation may be triggered while a different window's context is current
	// (e.g. when bindCompositorComponent is called after createAppWindowInternal pops
	// the editor window's context). VAOs are not shared between GL contexts.
	auto* ownerApp= getOwnerApp();
	auto* windowContext= m_mkWindowContext.get();
	ownerApp->getWindowManager()->pushCurrentWindowContext(windowContext);

	m_editorState.nodeGraph= createGraph();

	ownerApp->getWindowManager()->popCurrentWindowContext(windowContext);

	syncCurrentPageToGraph();
	onNodeGraphCreated();

	if (m_editorState.nodeGraph)
	{
		m_history.reset(m_editorState.nodeGraph->saveToSnapshotString());
		logGraphBaseline();
	}
}

void NodeEditorWindow::syncCurrentPageToGraph()
{
	NodeGraphPtr nodeGraph= getNodeGraph();
	if (!nodeGraph || !nodeGraph->hasPage(m_editorState.currentPageId))
	{
		m_editorState.currentPageId= NodeGraph::k_rootPageId;
	}
}

void NodeEditorWindow::setCurrentPage(t_graph_page_id pageId)
{
	NodeGraphPtr nodeGraph= getNodeGraph();
	if (pageId == m_editorState.currentPageId || !nodeGraph || !nodeGraph->hasPage(pageId))
	{
		return;
	}

	// Selections belong to the page that made them
	clearCanvasSelection();
	m_objectSelection.clear();

	m_editorState.currentPageId= pageId;

	// A hidden page's nodes keep their graph positions (the canvas only reads
	// back positions of nodes it draws), so push them to the canvas before it shows them
	if (m_canvasContext != nullptr)
	{
		ax::NodeEditor::EditorContext* prevContext= ed::GetCurrentEditor();
		ed::SetCurrentEditor(m_canvasContext);
		for (NodePtr pageNode : nodeGraph->getNodesOnPage(pageId))
		{
			const glm::vec2& nodePos= pageNode->getNodePos();
			ed::SetNodePosition(MkCanvas::toCanvasId(pageNode->getId()),
								MkCanvas::toCanvasSpace(ImVec2(nodePos.x, nodePos.y)));
		}
		ed::SetCurrentEditor(prevContext);
	}

	m_bNavigateToContentPending= true;
}

bool NodeEditorWindow::loadGraph(const std::filesystem::path& path)
{
	// Push this window's GL context before graph resource creation (VAOs, VBOs).
	// See comment in newGraph() for details.
	auto* ownerApp= getOwnerApp();
	auto* windowContext= m_mkWindowContext.get();
	ownerApp->getWindowManager()->pushCurrentWindowContext(windowContext);

	// A failed load keeps the graph the window already shows rather than leaving it empty
	NodeGraphPtr loadedGraph= NodeGraphFactory::loadNodeGraph(this, path);

	ownerApp->getWindowManager()->popCurrentWindowContext(windowContext);

	if (loadedGraph)
	{
		m_editorState.nodeGraph= loadedGraph;
		m_editorState.nodeGraphPath= path;
		syncCurrentPageToGraph();
		onNodeGraphCreated();
		m_history.reset(m_editorState.nodeGraph->saveToSnapshotString());
		logGraphBaseline();
		return true;
	}
	else
	{
		MIKAN_LOG_ERROR("NodeEditorWindow::load") << "Failed to load node graph: " << path;
	}

	return false;
}

std::filesystem::path NodeEditorWindow::getDefaultGraphDirectory() const { return PathUtils::getProjectDirectory(); }

bool NodeEditorWindow::saveGraph(bool bShowFileDialog)
{
	auto resolvedPath= PathUtils::resolveProjectResource(m_editorState.nodeGraphPath);
	ProjectAssetCatalog* catalog= getAssetCatalog();

	// A graph opened from the read-only bundled resources saves into the project
	// instead, at the path that shadows the bundled file
	const bool bReadOnlySource= catalog != nullptr && !resolvedPath.empty() && catalog->isReadOnlyPath(resolvedPath);

	// If no path was set (or non resolved) or we explicitly want to show the file dialog,
	// bring up the save path dialog
	if (resolvedPath.empty() || bShowFileDialog || bReadOnlySource)
	{
		std::filesystem::path defaultPath=
			getDefaultGraphDirectory() / (std::string("new_graph") + getGraphFileExtension());
		if (bReadOnlySource)
		{
			const std::filesystem::path shadowPath= ProjectAssetCatalog::makeProjectShadowPath(resolvedPath);
			if (!shadowPath.empty())
			{
				std::error_code ec;
				std::filesystem::create_directories(shadowPath.parent_path(), ec);
				defaultPath= shadowPath;
			}
		}
		const std::string defaultPathString= defaultPath.string();
		const std::string filterPattern= std::string("*") + getGraphFileExtension();
		const char* filterItems[1]= {filterPattern.c_str()};
		const char* filterDesc= locText(getGraphFilterDescriptionKey());

		const char* picked= tinyfd_saveFileDialog(locText(getSaveDialogTitleKey()), defaultPathString.c_str(), 1,
												  filterItems, filterDesc);

		// A cancelled dialog saves nothing, which is what keeps a bundled file untouched
		if (picked == nullptr || picked[0] == '\0')
		{
			return false;
		}

		resolvedPath= std::filesystem::path(picked);
		m_editorState.nodeGraphPath= PathUtils::makeStoredProjectPath(resolvedPath);
	}

	if (!resolvedPath.empty() && m_editorState.nodeGraph)
	{
		NodeGraphFactory::saveNodeGraph(resolvedPath, m_editorState.nodeGraph);

		// A save can land a new graph file in the project's graphs folder
		if (catalog != nullptr)
		{
			catalog->refresh();
		}

		return true;
	}

	return false;
}

void NodeEditorWindow::undo()
{
	// Applied at the top of the next update, outside the ImGui frame
	m_pendingHistorySteps-= 1;
}

void NodeEditorWindow::redo() { m_pendingHistorySteps+= 1; }

bool NodeEditorWindow::stepHistory(int steps)
{
	// Walk the cursor first so a multi-step request rebuilds the graph once
	const bool bIsUndo= steps < 0;
	int appliedSteps= 0;
	const std::string* targetSnapshot= nullptr;
	while (steps != 0)
	{
		const std::string* snapshot= bIsUndo ? m_history.undo() : m_history.redo();
		if (snapshot == nullptr)
		{
			break;
		}

		targetSnapshot= snapshot;
		appliedSteps++;
		steps+= bIsUndo ? 1 : -1;
	}

	if (targetSnapshot == nullptr)
	{
		return false;
	}

	if (!restoreGraphSnapshot(*targetSnapshot))
	{
		m_logWriter.writeEvent("restore_failed");
		return false;
	}

	m_logWriter.writeHistoryStep(bIsUndo ? "undo" : "redo", appliedSteps, m_history.getCursor(),
								 m_editorState.nodeGraph->saveToSnapshotConfig());

	return true;
}

bool NodeEditorWindow::restoreGraphSnapshot(const std::string& snapshot)
{
	m_bApplyingHistory= true;

	// Push this window's GL context before graph resource creation (VAOs, VBOs).
	// See comment in newGraph() for details.
	auto* ownerApp= getOwnerApp();
	auto* windowContext= m_mkWindowContext.get();
	ownerApp->getWindowManager()->pushCurrentWindowContext(windowContext);

	NodeGraphPtr restoredGraph= NodeGraphFactory::loadNodeGraphFromSnapshotString(this, snapshot);

	ownerApp->getWindowManager()->popCurrentWindowContext(windowContext);

	if (!restoredGraph)
	{
		MIKAN_LOG_ERROR("NodeEditorWindow::restoreGraphSnapshot") << "Failed to rebuild graph from snapshot";
		m_bApplyingHistory= false;
		return false;
	}

	// Swap in the restored graph using the same window plumbing a load uses
	onNodeGraphDeleted();
	m_editorState.nodeGraph= restoredGraph;
	m_editorState.startedLinkPinId= -1;
	m_editorState.bLinkHanged= false;
	syncCurrentPageToGraph();
	onNodeGraphCreated();

	// Stale selections may reference objects the snapshot does not contain
	{
		MkGuiScopedContext scopedContext(*m_guiContext.get());
		clearCanvasSelection();
	}
	m_objectSelection.clear();

	// Let subclasses rebind the restored graph to its owning component
	onGraphRestored();

	m_bCheckpointPending= false;
	m_bApplyingHistory= false;

	return true;
}

void NodeEditorWindow::updateHistoryCapture()
{
	if (m_bApplyingHistory)
	{
		return;
	}

	// Edits with no graph delegate (node property sheets, node drags) surface
	// as a widget going inactive or a mouse release; commit dedup drops false triggers
	const bool bAnyItemActive= ImGui::IsAnyItemActive();
	if ((m_bAnyItemActiveLastFrame && !bAnyItemActive) || ImGui::IsMouseReleased(ImGuiMouseButton_Left))
	{
		m_bCheckpointPending= true;
	}
	m_bAnyItemActiveLastFrame= bAnyItemActive;

	// Commit once the interaction settles, coalescing a burst (a delete
	// cascade, a whole drag) into a single undo step
	if (m_bCheckpointPending && !bAnyItemActive && !ImGui::IsMouseDown(ImGuiMouseButton_Left))
	{
		NodeGraphPtr nodeGraph= getNodeGraph();
		if (nodeGraph)
		{
			const configuru::Config snapshotConfig= nodeGraph->saveToSnapshotConfig();
			if (m_history.commit(configuru::dump_string(snapshotConfig, configuru::JSON)))
			{
				m_logWriter.writeSnapshotCommit(m_nextLogSequenceNumber++, snapshotConfig);
				onGraphEdited();
			}
		}
		m_bCheckpointPending= false;
	}
}

void NodeEditorWindow::refreshCanvasUiScale()
{
	const float uiScale= MkGui::getUiScale();
	if (uiScale == m_appliedCanvasUiScale)
	{
		return;
	}
	m_appliedCanvasUiScale= uiScale;

	NodeGraphPtr nodeGraph= getNodeGraph();
	if (!nodeGraph || m_canvasContext == nullptr)
	{
		return;
	}

	ax::NodeEditor::EditorContext* prevContext= ed::GetCurrentEditor();
	ed::SetCurrentEditor(m_canvasContext);
	for (auto iter= nodeGraph->getNodesMap().begin(); iter != nodeGraph->getNodesMap().end(); iter++)
	{
		NodePtr node= iter->second;
		const glm::vec2& nodePos= node->getNodePos();
		ed::SetNodePosition(MkCanvas::toCanvasId(iter->first), MkCanvas::toCanvasSpace(ImVec2(nodePos.x, nodePos.y)));

		// A comment box owns its size in the canvas, so it needs the same nudge
		if (auto commentNode= std::dynamic_pointer_cast<CommentNode>(node))
		{
			commentNode->applySizeOnNextDraw();
		}
	}
	ed::SetCurrentEditor(prevContext);
}

void NodeEditorWindow::clearCanvasSelection()
{
	if (m_canvasContext == nullptr)
	{
		return;
	}

	ax::NodeEditor::EditorContext* prevContext= ed::GetCurrentEditor();
	ed::SetCurrentEditor(m_canvasContext);
	ed::ClearSelection();
	ed::SetCurrentEditor(prevContext);
}

void NodeEditorWindow::logGraphBaseline()
{
	NodeGraphPtr nodeGraph= m_editorState.nodeGraph;
	if (!nodeGraph)
	{
		return;
	}

	// One log file per window session, opened when the first graph arrives.
	// Skipped when no project is loaded (the log lives in the project folder).
	if (!m_logWriter.isOpen())
	{
		ProjectManagerPtr projectManager= getProjectManager();
		ProjectConfigPtr projectConfig= projectManager ? projectManager->getProjectConfig() : nullptr;
		if (!projectConfig)
		{
			return;
		}

		std::string windowClassName= typeid(*this).name();
		if (windowClassName.rfind("class ", 0) == 0)
		{
			windowClassName= windowClassName.substr(6);
		}

		if (!m_logWriter.open(projectConfig->getLoadedConfigPath(), windowClassName))
		{
			return;
		}
	}

	m_logWriter.writeBaseline(m_editorState.nodeGraphPath, nodeGraph->getClassName(),
							  nodeGraph->saveToSnapshotConfig());
}

void NodeEditorWindow::enqueueAutomationTask(std::function<void()>&& task)
{
	m_automationTasks.push_back(std::move(task));
}

void NodeEditorWindow::flushAutomationTasks()
{
	while (!m_automationTasks.empty())
	{
		std::function<void()> task= std::move(m_automationTasks.front());
		m_automationTasks.erase(m_automationTasks.begin());
		task();
	}
}

