void NodeEditorWindow::renderCreateNodeMenu(const NodeEditorState& editorState)
{
	// A fresh popup starts with an empty filter and the keyboard in the filter box
	if (ImGui::IsWindowAppearing())
	{
		m_nodeSearchBuffer[0]= '\0';
		ImGui::SetKeyboardFocusHere();
	}
	ImGui::InputTextWithHint("##nodeSearch", locText("nodeEditor.searchNodes"), m_nodeSearchBuffer,
							 sizeof(m_nodeSearchBuffer));
	const std::string filter= m_nodeSearchBuffer;

	std::vector<NodeFactoryPtr> nodeFactories= getNodeGraph()->editorGetValidNodeFactories(editorState);

	// The picked factory is created after the menus close, so a pick inside a
	// submenu does not have to unwind through the category loop
	NodeFactoryPtr pickedFactory;
	const auto renderFactoryItem= [&](NodeFactoryPtr nodeFactory)
	{
		const std::string nodeTitle= nodeFactory->getNodeDefaultObject()->editorGetTitle();
		if (ImGui::MenuItem(nodeTitle.c_str()))
		{
			pickedFactory= nodeFactory;
		}
	};

	if (!filter.empty())
	{
		// A filter flattens the categories into one matching list
		for (NodeFactoryPtr nodeFactory : nodeFactories)
		{
			if (containsIgnoreCase(nodeFactory->getNodeDefaultObject()->editorGetTitle(), filter))
			{
				renderFactoryItem(nodeFactory);
			}
		}
	}
	else
	{
		// Uncategorized factories stay at the top level, the rest file under
		// their category submenu in sorted category order
		std::map<std::string, std::vector<NodeFactoryPtr>> categorizedFactories;
		for (NodeFactoryPtr nodeFactory : nodeFactories)
		{
			const std::string category= nodeFactory->editorGetCategory();
			if (category.empty())
			{
				renderFactoryItem(nodeFactory);
			}
			else
			{
				categorizedFactories[category].push_back(nodeFactory);
			}
		}

		for (const auto& categoryEntry : categorizedFactories)
		{
			if (ImGui::BeginMenu(categoryEntry.first.c_str()))
			{
				for (NodeFactoryPtr nodeFactory : categoryEntry.second)
				{
					renderFactoryItem(nodeFactory);
				}
				ImGui::EndMenu();
			}
		}
	}

	if (pickedFactory)
	{
		getNodeGraph()->createNode(pickedFactory, editorState);
	}
}

void NodeEditorWindow::renderGraphVariablesPanel()
{
	{
		MkGuiScopedStyle selectionStyle(m_styleManager->getStyle("node_editor_variable_list"));

		// A reorder mutates sort orders, so the drop is applied after the list
		// has finished rendering
		t_graph_property_id pendingReorderMovedId= -1;
		t_graph_property_id pendingReorderTargetId= -1;

		std::vector<GraphPropertyPtr> sortedProperties;
		if (getNodeGraph())
		{
			sortedProperties= getNodeGraph()->getPropertiesInSortOrder();
		}
		for (GraphPropertyPtr variable : sortedProperties)
		{
			const t_graph_property_id propertyId= variable->getId();

			// Variable
			const std::string varIcon= variable->editorGetIcon();
			const ImVec4& variconColor= variable->editorGetIconColor();
			ImGui::TextColored(variconColor, "%s", varIcon.c_str());
			ImGui::SameLine();

			// A row being renamed shows the field in place of its label and takes
			// no drag, drop, or context menu until the edit ends
			if (m_variableRename.isEditing(propertyId))
			{
				const MkGui::eInlineRenameResult result= MkGui::drawInlineRenameField(
					m_variableRename, StringUtils::stringify("##rename_property", std::to_string(propertyId)));
				if (result == MkGui::eInlineRenameResult::committed)
				{
					getNodeGraph()->renameProperty(propertyId, m_variableRename.buffer);
				}
				continue;
			}

			const std::string varEntryName=
				StringUtils::stringify(variable->getName(), "##property", std::to_string(propertyId));
			bool isSelected= m_objectSelection.getObjectIdType() == GraphObjectIdType::VARIABLE;
			isSelected= isSelected && (m_objectSelection.getObjectId(0) == variable->getId());
			// A click on the selected row keeps it selected: released in place it
			// starts the rename, dragged it carries the variable to the canvas
			if (ImGui::Selectable(varEntryName.c_str(), isSelected))
			{
				clearCanvasSelection();
				m_objectSelection= GraphObjectSelection(GraphObjectIdType::VARIABLE, 1);
				m_objectSelection.setObjectId(0, variable->getId());
			}
			if (MkGui::isRenameClickOnSelectedItem(isSelected, propertyId, m_variableRenamePressedId))
			{
				m_variableRename.begin(propertyId, variable->getName());
			}
			{
				MkGuiScopedDragDropSource dds(ImGuiDragDropFlags_None);
				if (dds)
				{
					ImGui::SetDragDropPayload(variable->getClassName().c_str(), &variable, sizeof(GraphPropertyPtr));
					ImGui::TextUnformatted(variable->getName().c_str());
				}
			}

			// Dropping a variable onto another row reorders the list. The row's
			// target only opens while that row is hovered, so dragging out to
			// the graph still creates a node instead.
			for (auto propertyFactory : getNodeGraph()->editorGetValidPropertyFactories(m_editorState))
			{
				auto droppedVariable=
					MkGui::receiveTypedDragDropPayload<GraphProperty>(propertyFactory->getGraphPropertyClassName());
				if (droppedVariable && droppedVariable->getId() != propertyId)
				{
					pendingReorderMovedId= droppedVariable->getId();
					pendingReorderTargetId= propertyId;
					break;
				}
			}

			// Context menu
			{
				MkGuiScopedStyle varContextMenuStyle(m_styleManager->getStyle("node_editor_context_menu"));
				MkGuiScopedPopupContextItem varContextMenu;
				if (varContextMenu)
				{
					clearCanvasSelection();
					m_objectSelection= GraphObjectSelection(GraphObjectIdType::VARIABLE, 1);
					m_objectSelection.setObjectId(0, variable->getId());

					if (ImGui::MenuItem(locLabel("nodeEditor.delete"), ICON_FK_TRASH, "DELETE"))
					{
						getNodeGraph()->deletePropertyById(propertyId);
						m_objectSelection.clear();
					}
				}
			}
		}

		if (pendingReorderMovedId != -1)
		{
			getNodeGraph()->reorderPropertyBefore(pendingReorderMovedId, pendingReorderTargetId);
		}
	}

	// Drag and drop creation (variables carry no canvas position)
	handleGraphVariablesDragDrop(m_editorState);

	renderNewGraphVariablesContextMenu(m_editorState);
}

